def themes_by_category(category):
    """Возвращает список (key, theme) в указанной категории."""
    result = []
    for key, t in THEMES.items():
        if key.startswith("custom_"):
            continue
        cat = t.get("category", "dark")
        if category == "all" or cat == category:
            result.append((key, t))
    return result


