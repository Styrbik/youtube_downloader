def get_theme(name):
    """Возвращает палитру по имени. Если нет — тёмная."""
    if name not in THEMES:
        try:
            from modules import theme_manager
            theme_manager.register_custom_themes(THEMES)
        except Exception:
            pass
    return THEMES.get(name, THEMES["dark"])